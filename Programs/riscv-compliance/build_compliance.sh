#!/bin/bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROGRAMS_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$PROGRAMS_DIR"

if command -v riscv-none-elf-gcc &> /dev/null; then
	PREFIX="riscv-none-elf-"
elif command -v riscv64-unknown-elf-gcc &> /dev/null; then
	PREFIX="riscv64-unknown-elf-"
elif command -v riscv32-unknown-elf-gcc &> /dev/null; then
	PREFIX="riscv32-unknown-elf-"
else
	echo "Error: No supported RISC-V GCC toolchain found in PATH."
	exit 1
fi

BSP_DIR="$PROGRAMS_DIR/bsp/multi_cycle"
# shellcheck source=/dev/null
source "$BSP_DIR/target.env"
TARGET_MARCH="${TARGET_MARCH:-rv32im_zicsr_zicntr}"

OUT_DIR="$PROGRAMS_DIR/out/multi_cycle/riscv_compliance"
rm -rf "$OUT_DIR"
mkdir -p "$OUT_DIR/objs"

ENV_DIR="$SCRIPT_DIR/env"
MACRO_DIR="$PROGRAMS_DIR/riscv-tests/isa/macros/scalar"
ISA_DIR="$PROGRAMS_DIR/riscv-tests/isa"

if [ ! -d "$ISA_DIR" ]; then
	echo "Cloning official riscv-tests into $PROGRAMS_DIR/riscv-tests ..."
	git clone --depth 1 https://github.com/riscv-software-src/riscv-tests.git "$PROGRAMS_DIR/riscv-tests"
fi

# Selected tests per suite:
# - rv32ui: all except fence_i (Zifencei not implemented) and ma_data (requires HW misaligned access)
RV32UI_TESTS=(
	simple
	add addi and andi auipc
	beq bge bgeu blt bltu bne
	jal jalr
	lb lbu lh lhu lw ld_st
	lui
	or ori
	sb sh sw st_ld
	sll slli slt slti sltiu sltu
	sra srai srl srli sub
	xor xori
)

# - rv32um: all 8 RV32M tests
RV32UM_TESTS=(
	mul mulh mulhsu mulhu
	div divu rem remu
)

# - rv32mi: synchronous M-mode trap/CSR/Zicntr tests
#   Skipped: breakpoint (Debug Triggers), pmpaddr (PMP),
#            {lh,lw,sh,sw}-misaligned (hardware misaligned load/store)
RV32MI_TESTS=(
	csr illegal instret_overflow ma_addr ma_fetch
	mcsr sbreak scall shamt zicntr
)

short_label() {
	case "$1" in
		simple) echo "SMPL" ;;
		auipc) echo "AUIP" ;;
		ld_st) echo "LDST" ;;
		st_ld) echo "STLD" ;;
		sltiu) echo "SLIU" ;;
		instret_overflow) echo "IOVF" ;;
		illegal) echo "ILLG" ;;
		ma_addr) echo "MAAD" ;;
		ma_fetch) echo "MAFT" ;;
		sbreak) echo "SBRK" ;;
		scall) echo "SCAL" ;;
		shamt) echo "SHMT" ;;
		zicntr) echo "ZCNT" ;;
		mulhsu) echo "MLHSU" ;;
		*) echo "$1" | tr '[:lower:]' '[:upper:]' | cut -c1-4 ;;
	esac
}

TEST_OBJS=()
TABLE_HEADER="$OUT_DIR/test_table.h"
{
	echo "/* Auto-generated by build_compliance.sh */"
	echo "#ifndef RISCV_COMPLIANCE_TEST_TABLE_H"
	echo "#define RISCV_COMPLIANCE_TEST_TABLE_H"
	echo ""
} > "$TABLE_HEADER"

TABLE_ENTRIES=""
TOTAL_COUNT=0

compile_suite() {
	local suite="$1"
	local suite_enum="$2"
	shift 2
	local tests=("$@")

	for name in "${tests[@]}"; do
		local src="$ISA_DIR/$suite/${name}.S"
		if [ ! -f "$src" ]; then
			echo "Error: Missing test file $src"
			exit 1
		fi
		local func="rvtest_${suite}_${name}"
		local obj="$OUT_DIR/objs/${suite}_${name}.o"

		"${PREFIX}gcc" -march="${TARGET_MARCH}" -mabi=ilp32 -O2 \
			-I"$ENV_DIR" -I"$MACRO_DIR" -I"$ISA_DIR/$suite" \
			-DTEST_FUNC_NAME="$func" \
			-c "$src" -o "$obj"

		"${PREFIX}objcopy" --keep-global-symbol="$func" "$obj"
		TEST_OBJS+=("$obj")

		local sname
		sname="$(short_label "$name")"
		echo "extern uint32_t ${func}(void);" >> "$TABLE_HEADER"
		TABLE_ENTRIES="${TABLE_ENTRIES}\t{ ${suite_enum}, \"${suite^^}\", \"${name}\", \"${sname}\", ${func} },\n"
		TOTAL_COUNT=$((TOTAL_COUNT + 1))
	done
}

echo "=================================================="
echo " Building Official RISC-V Compliance Suite"
echo " ISA:    ${TARGET_MARCH}"
echo " Output: ${OUT_DIR}"
echo "=================================================="

compile_suite "rv32ui" "SUITE_UI" "${RV32UI_TESTS[@]}"
compile_suite "rv32um" "SUITE_UM" "${RV32UM_TESTS[@]}"
compile_suite "rv32mi" "SUITE_MI" "${RV32MI_TESTS[@]}"

{
	echo ""
	echo "#define COMPLIANCE_TEST_COUNT $TOTAL_COUNT"
	echo ""
	echo "static const compliance_test_t compliance_tests[COMPLIANCE_TEST_COUNT] = {"
	printf "%b" "$TABLE_ENTRIES"
	echo "};"
	echo ""
	echo "#endif /* RISCV_COMPLIANCE_TEST_TABLE_H */"
} >> "$TABLE_HEADER"

CFLAGS=(-march="${TARGET_MARCH}" -mabi=ilp32 -O2 "-D${TARGET_MACRO}" -Ibsp/include -I"$OUT_DIR")

echo "[CC] $SCRIPT_DIR/main.c"
"${PREFIX}gcc" -c "${CFLAGS[@]}" "$SCRIPT_DIR/main.c" -o "$OUT_DIR/main.o"

echo "[CC] $BSP_DIR/hal.c"
"${PREFIX}gcc" -c "${CFLAGS[@]}" "$BSP_DIR/hal.c" -o "$OUT_DIR/hal.o"

echo "[CC] $PROGRAMS_DIR/lib/syscalls.c"
"${PREFIX}gcc" -c "${CFLAGS[@]}" "$PROGRAMS_DIR/lib/syscalls.c" -o "$OUT_DIR/syscalls.o"

echo "[AS] $BSP_DIR/boot.s"
"${PREFIX}as" -march="${TARGET_MARCH}" -mabi=ilp32 "$BSP_DIR/boot.s" -o "$OUT_DIR/boot.o"

echo "[LD] $OUT_DIR/program.elf"
"${PREFIX}gcc" -march="${TARGET_MARCH}" -mabi=ilp32 -T "$BSP_DIR/linker.ld" -nostartfiles \
	"$OUT_DIR/boot.o" "$OUT_DIR/main.o" "$OUT_DIR/hal.o" "$OUT_DIR/syscalls.o" \
	"${TEST_OBJS[@]}" \
	-Wl,--gc-sections -o "$OUT_DIR/program.elf"

"${PREFIX}objcopy" -O binary "$OUT_DIR/program.elf" "$OUT_DIR/program.bin"
"${PREFIX}size" "$OUT_DIR/program.elf"
ls -lh "$OUT_DIR/program.bin"
echo "Done: $TOTAL_COUNT compliance tests compiled."
